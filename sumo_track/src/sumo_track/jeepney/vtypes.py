"""Vehicle types (Phase 3, step 3): jeepney and car, all from config/params.yaml.

Writes data/processed/vtypes.add.xml. Sideways behaviour (latAlignment, minGapLat) follows
sandbox 10 and only takes effect when a run enables SUMO's sublane model; anything not set here
keeps SUMO's own default for that vehicle class. Colours and GUI shapes are display only.
The bicycle type comes with the commuter modes (Phase 4-5).

    python -m sumo_track.jeepney.vtypes
"""

from xml.sax.saxutils import quoteattr

from sumo_track.config import REPO_ROOT, Config
from sumo_track.network.build import OUT_DIR

OUT_FILE = OUT_DIR / "vtypes.add.xml"

# id -> (attribute -> params.yaml name, or a fixed display value in a tuple)
VTYPES = {
    "jeepney": {
        "vClass": "jeepney_vclass", "length": "jeepney_length", "width": "jeepney_width",
        "maxSpeed": "jeepney_max_speed", "accel": "jeepney_accel", "decel": "jeepney_decel",
        "personCapacity": "jeepney_capacity", "boardingDuration": "boarding_time_per_pax",
        "latAlignment": "jeepney_lat_alignment",
        "color": ("1,0.8,0",), "guiShape": ("bus",),
    },
    "car": {
        "vClass": ("passenger",), "latAlignment": "car_lat_alignment", "minGapLat": "car_min_gap_lat",
        "color": ("0.75,0.75,0.75",),
    },
}


def vtypes_xml(config) -> str:
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- Generated by python -m sumo_track.jeepney.vtypes from config/params.yaml.",
             "     Do not edit: change params.yaml and rebuild. -->",
             "<additional>"]
    for vtype_id, attrs in VTYPES.items():
        values = {k: v[0] if isinstance(v, tuple) else config.param(v) for k, v in attrs.items()}
        attr_text = " ".join(f"{k}={quoteattr(str(v))}" for k, v in values.items())
        lines.append(f'    <vType id="{vtype_id}" {attr_text}/>')
    lines.append("</additional>")
    return "\n".join(lines) + "\n"


def main() -> None:
    config = Config.load()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(vtypes_xml(config), encoding="utf-8")
    print(f"Wrote {OUT_FILE.relative_to(REPO_ROOT).as_posix()} ({', '.join(VTYPES)})")


if __name__ == "__main__":
    main()
