"""Jeepney service (Phase 3, step 4): one route and one flow per matched jeepney route.

Reads data/processed/jeepney_routes.matched.json (python -m sumo_track.jeepney.route_match) and
writes data/processed/jeepney.rou.xml: every route gets a jeepney every jeepney_headway seconds
for the whole day (0 to day_length_s). The flow's line is the route id, which is what commuters'
rides will name later (Phase 5).

    python -m sumo_track.jeepney.flows
"""

import json

from sumo_track.config import REPO_ROOT, Config
from sumo_track.jeepney.route_match import OUT_FILE as MATCHED_FILE
from sumo_track.network.build import OUT_DIR

OUT_FILE = OUT_DIR / "jeepney.rou.xml"


def flows_xml(routes, headway_s, day_length_s) -> str:
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- Generated by python -m sumo_track.jeepney.flows. Do not edit: rebuild. -->",
             "<routes>"]
    for r in routes:
        lines.append(f'    <route id="r_{r["route_id"]}" edges="{" ".join(r["edges"])}"/>')
    # flows all begin at 0; SUMO wants route-file entries in departure order
    for r in routes:
        lines.append(f'    <flow id="{r["route_id"]}" type="jeepney" route="r_{r["route_id"]}" '
                     f'line="{r["route_id"]}" begin="0" end="{day_length_s}" period="{headway_s}" '
                     f'departLane="best"/>')
    lines.append("</routes>")
    return "\n".join(lines) + "\n"


def main() -> None:
    config = Config.load()
    if not MATCHED_FILE.is_file():
        raise SystemExit("No matched routes yet: run python -m sumo_track.jeepney.route_match first")
    routes = json.loads(MATCHED_FILE.read_text(encoding="utf-8"))["routes"]
    headway, day = config.param("jeepney_headway"), config.param("day_length_s")
    OUT_FILE.write_text(flows_xml(routes, headway, day), encoding="utf-8")
    print(f"Wrote {OUT_FILE.relative_to(REPO_ROOT).as_posix()}: {len(routes)} jeepney routes, "
          f"one jeepney every {headway} s each, 0-{day} s")


if __name__ == "__main__":
    main()
