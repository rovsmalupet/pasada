"""Write demand.rou.xml: jeepneys, cars, MOTORCYCLES, flagging commuters.

Same idea as sandbox 10, plus motorcycles and a signalised cross street.
Seeded, so re-running gives the same file.

    python make_demand.py
"""
import os
import random
import sys

if "SUMO_HOME" in os.environ:
    sys.path.append(os.path.join(os.environ["SUMO_HOME"], "tools"))

import sumolib
from sumolib import geomhelper

HERE = os.path.dirname(os.path.abspath(__file__))

# ============================ SETTINGS ====================================
SEED = 7
SIM_END = 2400                 # s
JEEPNEY_HEADWAY = 90           # s, each direction
CARS_PER_HOUR = 550            # main road, each direction
MOTOS_PER_HOUR = 550           # main road, each direction
CROSS_PER_HOUR = 150           # cross street, each direction (cars + motos)
N_COMMUTERS = 50
COMMUTER_WINDOW = (30, 1800)
MARKET_X = (250.0, 550.0)      # most boardings happen here (world x, m)
MARKET_SHARE = 0.7
JUNCTION_X = 800.0             # keep jeepney stops away from the signal
JUNCTION_CLEAR = 60.0

# --- motorcycle behaviour (all placeholders for params.yaml) ---------------
MOTO_WIDTH = 0.75              # m  typical scooter (SUMO default is 0.9)
MOTO_MIN_GAP_LAT = 0.15        # m  sideways clearance it accepts when filtering.
                               #    Tested 0.05 too: ~15% more kerb-side filtering,
                               #    but 5 cm is needlessly aggressive.
MOTO_LAT_ALIGNMENT = "arbitrary"   # no preferred spot in the lane: go wherever
                                   # there is room (see the comment in the XML)
# ==========================================================================

net = sumolib.net.readNet(os.path.join(HERE, "road.net.xml"))

# direction -> ordered edges, and the x-range each edge covers
ROUTE = {"EB": ["AC", "CB"], "WB": ["BC", "CA"]}


def road_lane(edge_id):
    for lane in net.getEdge(edge_id).getLanes():
        if lane.allows("passenger"):
            return lane
    raise ValueError(edge_id)


def locate(direction, x):
    """World x on the main road -> (edge, pos along that edge)."""
    for eid in ROUTE[direction]:
        shape = road_lane(eid).getShape()
        xs = sorted((shape[0][0], shape[-1][0]))
        if xs[0] + 1.0 <= x <= xs[1] - 1.0:
            pos, _ = geomhelper.polygonOffsetAndDistanceToPoint((x, shape[0][1]), shape)
            return eid, round(pos, 1)
    return None


def pick_board_x(rng):
    while True:
        x = rng.uniform(*MARKET_X) if rng.random() < MARKET_SHARE else rng.uniform(80, 1120)
        if abs(x - JUNCTION_X) > JUNCTION_CLEAR:
            return x


def commuter_plan(rng, direction):
    sign = 1 if direction == "EB" else -1
    for _ in range(200):
        bx = pick_board_x(rng)
        hx = bx - sign * rng.uniform(15.0, 50.0)       # home: walk TO the kerb spot
        ax = bx + sign * rng.uniform(180.0, 380.0)     # alight further along
        dx = ax + sign * rng.uniform(10.0, 40.0)       # short walk after
        if abs(ax - JUNCTION_X) <= JUNCTION_CLEAR:
            continue
        home, board, alight, dest = (locate(direction, v) for v in (hx, bx, ax, dx))
        if None in (home, board, alight, dest):
            continue
        if home[0] != board[0] or alight[0] != dest[0]:
            continue                                   # walks stay on one edge
        return home, board, alight, dest
    raise RuntimeError("could not place a commuter")


def main():
    rng = random.Random(SEED)
    p_car, p_moto, p_cross = (CARS_PER_HOUR / 3600.0, MOTOS_PER_HOUR / 3600.0,
                              CROSS_PER_HOUR / 3600.0)
    out = []
    w = out.append
    w('<?xml version="1.0" encoding="UTF-8"?>')
    w("<!-- GENERATED by make_demand.py (seed %d) - edit that, not this. -->" % SEED)
    w("<routes>")
    w("""
    <!-- ===================== vehicle types =====================
         Every number is a placeholder for params.yaml.

         jeepney / car: as in sandbox 10 (jeepney hugs the kerb, cars use
         latAlignment="nice" when squeezing past it).

         motorcycle: width %.2f m (a scooter; SUMO's default is 0.9 m).
           latAlignment="%s" - no preferred position in the lane, so it
             drifts to whichever strips are free: the kerb side of a queue,
             the centre-line side, or between two vehicles. Tested against
             "center": that kept pulling motorcycles back to mid-lane while
             still beside a car - 14 collisions vs 0.
           minGapLat=%.2f m - how close it is willing to pass alongside.
           minGap=1.0 m - it closes up tighter than a car (2.5 m default).
           The 0.4 m strips (sim.sumocfg) matter as much as these: with
           0.8 m strips the last strip of a 3.6 m lane is only 0.4 m wide,
           and centre-line-side filtering fell from 1053 passes to 56. -->
    <vType id="jeepney" vClass="bus" length="7.0" width="2.1"
           maxSpeed="11.11" accel="1.0" decel="3.0"
           personCapacity="16" boardingDuration="2.0"
           latAlignment="right" minGapLat="0.4"
           color="1,0.8,0" guiShape="bus"/>
    <vType id="car_eb" vClass="passenger" width="1.8" length="4.5"
           latAlignment="nice" minGapLat="0.4" speedDev="0.1" color="0.3,0.6,1"/>
    <vType id="car_wb" vClass="passenger" width="1.8" length="4.5"
           latAlignment="nice" minGapLat="0.4" speedDev="0.1" color="1,0.35,0.35"/>
    <vType id="moto_eb" vClass="motorcycle" length="2.0" width="%.2f" minGap="1.0"
           maxSpeed="16.67" accel="3.0" decel="6.0" speedDev="0.15"
           latAlignment="%s" minGapLat="%.2f"
           color="0.1,0.9,0.9" guiShape="motorcycle"/>
    <vType id="moto_wb" vClass="motorcycle" length="2.0" width="%.2f" minGap="1.0"
           maxSpeed="16.67" accel="3.0" decel="6.0" speedDev="0.15"
           latAlignment="%s" minGapLat="%.2f"
           color="1,0.55,0.1" guiShape="motorcycle"/>
    <vType id="car_ns" vClass="passenger" width="1.8" length="4.5" color="0.6,0.6,0.6"/>
    <vType id="moto_ns" vClass="motorcycle" length="2.0" width="%.2f" minGap="1.0"
           latAlignment="%s" minGapLat="%.2f" color="0.6,0.6,0.6" guiShape="motorcycle"/>
    <vType id="pedestrian" vClass="pedestrian" speed="1.34"/>

    <route id="r_eb" edges="AC CB"/>
    <route id="r_wb" edges="BC CA"/>
    <route id="r_ns" edges="NC CS"/>
    <route id="r_sn" edges="SC CN"/>"""
      % (MOTO_WIDTH, MOTO_LAT_ALIGNMENT, MOTO_MIN_GAP_LAT,
         MOTO_WIDTH, MOTO_LAT_ALIGNMENT, MOTO_MIN_GAP_LAT,
         MOTO_WIDTH, MOTO_LAT_ALIGNMENT, MOTO_MIN_GAP_LAT,
         MOTO_WIDTH, MOTO_LAT_ALIGNMENT, MOTO_MIN_GAP_LAT))

    w("""
    <!-- ===================== flows (all begin at 0, so they come first) =====
         Main road, EACH direction: %d cars/h + %d motorcycles/h.
         Cross street: %d/h each way, half cars, half motorcycles. -->
    <flow id="JEEP_EB" type="jeepney" route="r_eb" line="JEEP_EB" begin="0" end="%d" period="%d"/>
    <flow id="JEEP_WB" type="jeepney" route="r_wb" line="JEEP_WB" begin="0" end="%d" period="%d"/>
    <flow id="car_EB"  type="car_eb"  route="r_eb" begin="0" end="%d" probability="%.4f"/>
    <flow id="car_WB"  type="car_wb"  route="r_wb" begin="0" end="%d" probability="%.4f"/>
    <flow id="moto_EB" type="moto_eb" route="r_eb" begin="0" end="%d" probability="%.4f"/>
    <flow id="moto_WB" type="moto_wb" route="r_wb" begin="0" end="%d" probability="%.4f"/>
    <flow id="car_NS"  type="car_ns"  route="r_ns" begin="0" end="%d" probability="%.4f"/>
    <flow id="car_SN"  type="car_ns"  route="r_sn" begin="0" end="%d" probability="%.4f"/>
    <flow id="moto_NS" type="moto_ns" route="r_ns" begin="0" end="%d" probability="%.4f"/>
    <flow id="moto_SN" type="moto_ns" route="r_sn" begin="0" end="%d" probability="%.4f"/>"""
      % (CARS_PER_HOUR, MOTOS_PER_HOUR, CROSS_PER_HOUR,
         SIM_END - 300, JEEPNEY_HEADWAY, SIM_END - 300, JEEPNEY_HEADWAY,
         SIM_END, p_car, SIM_END, p_car, SIM_END, p_moto, SIM_END, p_moto,
         SIM_END, p_cross / 2, SIM_END, p_cross / 2,
         SIM_END, p_cross / 2, SIM_END, p_cross / 2))

    people = []
    for i in range(N_COMMUTERS):
        direction = "EB" if i % 2 == 0 else "WB"
        depart = rng.uniform(*COMMUTER_WINDOW)
        home, board, alight, dest = commuter_plan(rng, direction)
        people.append((depart, "c%02d_%s" % (i, direction), direction,
                       home, board, alight, dest))
    people.sort()

    w("""
    <!-- ===================== commuters =====================
         walk to the kerb spot -> ride -> walk on. run.py reads the boarding
         point (end of the first walk) and alighting point (the ride's
         to + arrivalPos) from here. -->""")
    for depart, pid, direction, home, board, alight, dest in people:
        w('    <person id="%s" type="pedestrian" depart="%.1f" departPos="%.1f">'
          % (pid, depart, home[1]))
        w('        <walk from="%s" to="%s" arrivalPos="%.1f"/>' % (home[0], board[0], board[1]))
        w('        <ride from="%s" to="%s" lines="JEEP_%s" arrivalPos="%.1f"/>'
          % (board[0], alight[0], direction, alight[1]))
        w('        <walk from="%s" to="%s" arrivalPos="%.1f"/>' % (alight[0], dest[0], dest[1]))
        w("    </person>")
    w("</routes>")

    open(os.path.join(HERE, "demand.rou.xml"), "w").write("\n".join(out) + "\n")
    print("wrote demand.rou.xml: %d commuters | main road each way: %d cars/h + %d "
          "motorcycles/h | jeepney every %d s" % (N_COMMUTERS, CARS_PER_HOUR,
                                                  MOTOS_PER_HOUR, JEEPNEY_HEADWAY))


if __name__ == "__main__":
    main()
