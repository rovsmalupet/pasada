"""Write demand.rou.xml: jeepneys, lots of cars both ways, flagging commuters.

Seeded, so re-running gives the same file. Change the numbers in the
SETTINGS block and re-run to make traffic lighter or heavier.

    python make_demand.py
"""
import os
import random
import sys

if "SUMO_HOME" in os.environ:
    sys.path.append(os.path.join(os.environ["SUMO_HOME"], "tools"))

import sumolib

HERE = os.path.dirname(os.path.abspath(__file__))

# ============================ SETTINGS ====================================
SEED = 7
SIM_END = 2400                 # s
JEEPNEY_HEADWAY = 90           # s, each direction
CARS_PER_HOUR = 700            # each direction (prototype used ~240).
                               # Tested: 900 leaves almost no gaps in the
                               # oncoming lane, so cars just queue (5 overtakes).
N_COMMUTERS = 50               # split between the two directions
COMMUTER_WINDOW = (30, 1800)   # departure times are spread over this range
# Most boardings happen along a "market stretch" so the default GUI view
# catches the action. World x-coordinates, metres from the west end.
MARKET_X = (350.0, 650.0)
MARKET_SHARE = 0.7
# ==========================================================================

net = sumolib.net.readNet(os.path.join(HERE, "road.net.xml"))


def edge_start_x(edge_id):
    shape = net.getEdge(edge_id).getLanes()[0].getShape()
    return shape[0][0]


def x_to_pos(edge_id, x):
    """World x -> position along the edge (edges run in opposite directions)."""
    x0 = edge_start_x(edge_id)
    return x - x0 if edge_id == "AB" else x0 - x


def pick_board_x(rng):
    if rng.random() < MARKET_SHARE:
        return rng.uniform(*MARKET_X)
    return rng.uniform(120.0, 1000.0)


def commuter_plan(rng, direction):
    """(edge, depart_pos, board_pos, alight_pos, dest_pos) along one edge."""
    edge = "AB" if direction == "EB" else "BA"
    length = net.getEdge(edge).getLength()
    for _ in range(100):
        bx = pick_board_x(rng)
        board = x_to_pos(edge, bx)
        home = board - rng.uniform(15.0, 50.0)          # walk TO the kerb spot
        alight = board + rng.uniform(180.0, 380.0)       # ride further along
        dest = alight + rng.uniform(10.0, 40.0)          # short walk after
        if home > 5.0 and dest < length - 5.0:
            return edge, round(home, 1), round(board, 1), round(alight, 1), round(dest, 1)
    raise RuntimeError("could not place a commuter on %s" % edge)


def main():
    rng = random.Random(SEED)
    prob = CARS_PER_HOUR / 3600.0

    out = []
    w = out.append
    w('<?xml version="1.0" encoding="UTF-8"?>')
    w("<!-- GENERATED by make_demand.py (seed %d) - edit that, not this. -->" % SEED)
    w("<routes>")
    w("""
    <!-- ===================== vehicle types =====================
         Every number is a placeholder for params.yaml.

         jeepney: latAlignment="right" keeps it on the kerb side of its lane
                  (and that is where it stops to load). width 2.1 m.
         car:     latAlignment="nice" = sit wherever you cover the FEWEST
                  0.8 m strips. Squeezing past a kerbside jeepney, that is
                  "use the strip left in my lane + just enough of the
                  oncoming lane". Tested against "center", which re-centres
                  the car in the oncoming lane once its middle crosses the
                  line (15 of 23 overtakes went fully across, vs 5 of 25).
                  minGapLat = sideways clearance kept when squeezing past. -->
    <vType id="jeepney" vClass="bus" length="7.0" width="2.1"
           maxSpeed="11.11" accel="1.0" decel="3.0"
           personCapacity="16" boardingDuration="2.0"
           latAlignment="right" minGapLat="0.4"
           color="1,0.8,0" guiShape="bus"/>
    <vType id="car_eb" vClass="passenger" width="1.8" length="4.5"
           latAlignment="nice" minGapLat="0.4"
           speedDev="0.1" color="0.3,0.6,1"/>
    <vType id="car_wb" vClass="passenger" width="1.8" length="4.5"
           latAlignment="nice" minGapLat="0.4"
           speedDev="0.1" color="1,0.35,0.35"/>
    <vType id="pedestrian" vClass="pedestrian" speed="1.34"/>

    <route id="r_eb" edges="AB"/>
    <route id="r_wb" edges="BA"/>""")

    # Flows first: they all begin at t=0, and SUMO drops entries that are out
    # of departure order relative to earlier ones in the file.
    w("""
    <!-- ===================== jeepneys (one line each way) ===================== -->
    <flow id="JEEP_EB" type="jeepney" route="r_eb" line="JEEP_EB"
          begin="0" end="%d" period="%d"/>
    <flow id="JEEP_WB" type="jeepney" route="r_wb" line="JEEP_WB"
          begin="0" end="%d" period="%d"/>""" % (SIM_END - 300, JEEPNEY_HEADWAY,
                                               SIM_END - 300, JEEPNEY_HEADWAY))
    w("""
    <!-- ===================== cars: %d per hour EACH way =====================
         probability = chance per second that a car enters, so they arrive in
         random bunches and gaps, like real traffic. Blue = eastbound,
         red = westbound. -->
    <flow id="car_EB" type="car_eb" route="r_eb" begin="0" end="%d" probability="%.4f"/>
    <flow id="car_WB" type="car_wb" route="r_wb" begin="0" end="%d" probability="%.4f"/>"""
      % (CARS_PER_HOUR, SIM_END, prob, SIM_END, prob))

    people = []
    for i in range(N_COMMUTERS):
        direction = "EB" if i % 2 == 0 else "WB"
        depart = rng.uniform(*COMMUTER_WINDOW)
        edge, home, board, alight, dest = commuter_plan(rng, direction)
        people.append((depart, "c%02d_%s" % (i, direction), direction,
                       edge, home, board, alight, dest))
    people.sort()

    w("""
    <!-- ===================== commuters =====================
         walk along the sidewalk to the kerb spot -> ride -> walk on.
         The controller (run.py) reads boarding/alighting points from here:
           boarding  = where the first walk ends  (to + arrivalPos)
           alighting = the ride's own             (to + arrivalPos) -->""")
    for depart, pid, direction, edge, home, board, alight, dest in people:
        line = "JEEP_" + direction
        w('    <person id="%s" type="pedestrian" depart="%.1f" departPos="%.1f">'
          % (pid, depart, home))
        w('        <walk from="%s" to="%s" arrivalPos="%.1f"/>' % (edge, edge, board))
        w('        <ride from="%s" to="%s" lines="%s" arrivalPos="%.1f"/>'
          % (edge, edge, line, alight))
        w('        <walk from="%s" to="%s" arrivalPos="%.1f"/>' % (edge, edge, dest))
        w("    </person>")
    w("</routes>")

    path = os.path.join(HERE, "demand.rou.xml")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote %s: %d commuters, %d cars/h each way, jeepney every %d s each way"
          % (os.path.basename(path), N_COMMUTERS, CARS_PER_HOUR, JEEPNEY_HEADWAY))


if __name__ == "__main__":
    main()
